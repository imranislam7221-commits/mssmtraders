const BN_ON = ['','এক','দুই','তিন','চার','পাঁচ','ছয়','সাত','আট','নয়','দশ','এগারো','বারো','তেরো','চৌদ্দ','পনেরো','ষোলো','সতেরো','আঠারো','উনিশ','বিশ','একুশ','বাইশ','তেইশ','চব্বিশ','পঁচিশ','ছাব্বিশ','সাতাশ','আটাশ','উনত্রিশ'];
const BN_TENS = ['','','বিশ','ত্রিশ','চল্লিশ','পঞ্চাশ','ষাট','সত্তর','আশি','নব্বই'];
function bnDigits(x){ return String(x).replace(/[0-9]/g, d => '০১২৩৪৫৬৭৮৯'[+d]); }
function bnTwo(n){ if (n <= 29) return BN_ON[n]; const t = Math.floor(n / 10), o = n % 10; return BN_TENS[t] + (o ? ' ' + BN_ON[o] : ''); }
function banglaMoneyWords(n){
  n = Math.round(+n || 0);
  if (!n) return 'শূন্য';
  const parts = [];
  const cr = Math.floor(n / 10000000); if (cr) parts.push(banglaMoneyWords(cr) + ' কোটি');
  n = n % 10000000;
  const lk = Math.floor(n / 100000); if (lk) parts.push(bnTwo(lk) + ' লক্ষ');
  n = n % 100000;
  const th = Math.floor(n / 1000); if (th) parts.push(bnTwo(th) + ' হাজার');
  n = n % 1000;
  const hu = Math.floor(n / 100); if (hu) parts.push(BN_ON[hu] + 'শ');
  n = n % 100;
  if (n) parts.push(bnTwo(n));
  return parts.join(' ');
}
